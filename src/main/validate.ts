/**
 * Argument checks for ipc handlers. Everything that arrives from a renderer is
 * untrusted: these throw on anything that is not exactly the expected shape.
 * Kept free of Electron imports so it can be unit-tested.
 */

export const LIMITS = {
  /** Ops in one `blocks:apply`, ids in one `blocks:getMany`. */
  batch: 20_000,
  /** Serialized size of one `blocks:apply` batch, in UTF-16 code units. */
  batchChars: 32 * 1024 * 1024,
  query: 1000,
  settingKey: 128,
  settingChars: MAX_SETTING_CHARS,
  clientId: 64,
  errorMessage: 300,
  /** A picture generated by the renderer (a chart) that the user saves to a file. */
  generatedImageBytes: 20 * 1024 * 1024
} as const

const CLIENT_ID_RE = /^[A-Za-z0-9_-]+$/
const SETTING_KEY_RE = /^[A-Za-z][A-Za-z0-9_-]*(\.[A-Za-z0-9_-]+)*$/
/**
 * Exact keys the renderer may write. The `history.*` ones are the four the History settings show,
 * the `ai.*` ones the five the AI settings show, the `herman.*` ones those the Herman settings show,
 * the seats of his council among them (what he remembers, `herman.memory`, is not); `updates.check`
 * (not `updates.lastCheck`); `mcp.enabled`; nothing else in those namespaces.
 */
const WRITABLE_SETTINGS: ReadonlySet<string> = new Set(['theme', 'appearance', HOME_SETTING, ...HISTORY_KEYS, ...AI_KEYS, ...BRIEFING_KEYS, ...MEETINGS_KEYS, ...HERMAN_KEYS, ...UPDATES_KEYS, ...MCP_KEYS, ...NOTEBOOK_KEYS, ...ALARMS_KEYS, ...POMODORO_KEYS, SIDEBAR_SETTING])
/** `<namespace>.<anything>` keys the renderer may write; everything else belongs to the main process. */
const WRITABLE_NAMESPACES: ReadonlySet<string> = new Set(['shell', 'database', 'editor', 'appearance', 'ui'])

export function id(value: unknown, what = 'id'): string {
  if (!isValidId(value)) throw new Error(`Invalid ${what}`)
  return value
}

export function nullableId(value: unknown, what = 'id'): string | null {
  return value === null || value === undefined ? null : id(value, what)
}

/** `undefined` = append, `null` = first, otherwise the sibling to insert after. */
export function afterId(value: unknown): string | null | undefined {
  return value === undefined || value === null ? value : id(value, 'afterId')
}

export function optionalId(value: unknown, what = 'id'): string | undefined {
  return value === undefined || value === null ? undefined : id(value, what)
}

export function plainObject(value: unknown, what: string): Record<string, unknown> {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) throw new Error(`Invalid ${what}`)
  const proto: unknown = Object.getPrototypeOf(value)
  if (proto !== Object.prototype && proto !== null) throw new Error(`Invalid ${what}`)
  return value as Record<string, unknown>
}

export function list(value: unknown, what: string, max: number = LIMITS.batch): unknown[] {
  if (!Array.isArray(value)) throw new Error(`Invalid ${what}`)
  if (value.length > max) throw new Error(`Too many ${what}`)
  return value
}

export function idList(value: unknown, what: string): string[] {
  return list(value, what).map((x) => id(x, what))
}

/** Result-count limits; the repository clamps the range, this only rejects non-numbers. */
export function limit(value: unknown): number | undefined {
  if (value === undefined || value === null) return undefined
  if (typeof value !== 'number' || !Number.isFinite(value)) throw new Error('Invalid limit')
  return value
}

export function text(value: unknown, what: string, max: number): string {
  if (typeof value !== 'string' || value.length > max) throw new Error(`Invalid ${what}`)
  return value
}

export function clientId(value: unknown): string {
  if (typeof value !== 'string' || !value || value.length > LIMITS.clientId || !CLIENT_ID_RE.test(value)) {
    throw new Error('Invalid client id')
  }
  return value
}

const PNG_MAGIC = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]
/** Signature (8) + the length, type and start of the IHDR chunk every PNG begins with. */
const PNG_MIN_BYTES = 24

/**
 * The bytes of a PNG a renderer generated: binary data (never a string or an array of
 * numbers), within the size cap, starting with the PNG signature and its IHDR chunk.
 * Returns a copy the caller owns.
 */
export function pngBytes(value: unknown, max: number = LIMITS.generatedImageBytes): Uint8Array {
  let view: Uint8Array
  if (value instanceof ArrayBuffer) view = new Uint8Array(value)
  else if (ArrayBuffer.isView(value)) view = new Uint8Array(value.buffer, value.byteOffset, value.byteLength)
  else throw new Error('Invalid image data')
  if (view.byteLength > max) throw new Error(`The image is too large (max ${Math.floor(max / 1024 / 1024)} MB)`)
  if (view.byteLength < PNG_MIN_BYTES || PNG_MAGIC.some((byte, index) => view[index] !== byte)) throw new Error('The image is not a PNG')
  if (String.fromCharCode(view[12], view[13], view[14], view[15]) !== 'IHDR') throw new Error('The image is not a PNG')
  return view.slice()
}

/** Throws unless `value` serializes to JSON within `max` UTF-16 code units. */
export function sized<T>(value: T, what: string, max: number): T {
  let length: number
  try {
    const json: unknown = JSON.stringify(value)
    length = typeof json === 'string' ? json.length : 0
  } catch {
    throw new Error(`Invalid ${what}`)
  }
  if (length > max) throw new Error(`${what} is too large`)
  return value
}

/** A batch of ops: bounded in count and total size. Each op is validated by the repository. */
export function ops(value: unknown): unknown[] {
  const out = list(value, 'ops')
  for (const op of out) plainObject(op, 'op')
  return sized(out, 'ops', LIMITS.batchChars)
}

/** A syntactically valid settings key (readable by the renderer). */
export function settingKey(value: unknown): string {
  const key = text(value, 'setting key', LIMITS.settingKey)
  if (!SETTING_KEY_RE.test(key)) throw new Error('Invalid setting key')
  return key
}

export function isWritableSetting(key: string): boolean {
  if (WRITABLE_SETTINGS.has(key)) return true
  const dot = key.indexOf('.')
  return dot > 0 && WRITABLE_NAMESPACES.has(key.slice(0, dot))
}

/** A settings key the renderer is allowed to write. */
export function writableSettingKey(value: unknown): string {
  const key = settingKey(value)
  if (!isWritableSetting(key)) throw new Error(`Setting "${key}" is read-only`)
  return key
}

export function settingValue(value: unknown): unknown {
  return value === undefined || value === null ? null : sized(value, 'Setting value', LIMITS.settingChars)
}

/**
 * The value stored for a writable key. The history and AI settings steer the main process, so
 * they are typed; for history: a boolean, or a number brought into its range; null resets one to its default.
 */
export function settingValueFor(key: string, value: unknown): unknown {
  if (key.startsWith('ai.')) return aiSettingValue(key, value)
  if (key.startsWith('briefing.')) return briefingSettingValue(key, value)
  if (key.startsWith('meetings.')) return meetingsSettingValue(key, value)
  if (key.startsWith('herman.')) return hermanSettingValue(key, value)
  if (key.startsWith('updates.')) return updatesSettingValue(key, value)
  if (key.startsWith('mcp.')) return mcpSettingValue(key, value)
  if (key.startsWith('notebook.')) return notebookSettingValue(key, value)
  if (key.startsWith('alarms.')) return alarmsSettingValue(key, value)
  if (key === HOME_SETTING) return homeSettingValue(value)
  if (key === STARTUP_SETTING) return startupSettingValue(value)
  if (key === SIDEBAR_SETTING) return sidebarSettingValue(value)
  if (key.startsWith('pomodoro.')) return pomodoroSettingValue(key, value)
  if (!key.startsWith('history.')) return settingValue(value)
  if (value === undefined || value === null) return null
  const clean = cleanHistorySetting(key, value)
  if (clean === undefined) throw new Error('Invalid setting value')
  return clean
}

